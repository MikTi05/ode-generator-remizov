        'Контроли взяты из30 разных семейств, не пересекающихся с14 семействами проблемной группы: '
        'стратификация по20 ячейкам сложности/режима, SHA-выбор seed2488. '
        'Отбор и GO-критерий записаны до новых zero-ответов; доступность и ошибки zero не использованы для отбора. '
        'Из development исключены исторические Test-семейства/топологии. Один прежний экстремальный '
        'пример F0180/S04 принадлежит Test и в новой оценке не участвует. '
        'Три отсутствующих development-ответа R не имеют измеренной E33 и не заменены искусственной ошибкой; '
        'они не входят в52 задачи. План/selection фиксируют все ID.','',
        'Использованы сохранённые исходные taper-ответы на33 узлах G33={−1+k/16:k=0,…,32}; '
        'их ошибка перепроверена как max|f−exact|. Новых taper-расчётов0. '
        'Подтверждены одинаковые metadata/exact/config, эффективный T и SHA массивов '
        'a,b,c_R,g_R, пространственных узлов, временных узлов/весов и target_x. '
        'В zero изменено ровно boundary: n=128, num_t=513, quadratic, dx=.0125, '
        'padding=12, окно[-13,13] из2081 узла, tail_eps=1e−8, T=None, '
        'taper_width=None, n_jobs=1 и все остальные поля сохранены. '
        'Время T по каждому ID совпадает точно с baseline; точные решения не менялись.','',
        f"Из исторических результатов повторно использованы {s['reused_zero']} совместимых cubic/zero; "
        f"новых zero-вызовов {s['new_zero_calls']}. Другие620 обнаруженных zero-записей имеют "
        'несовместимые параметры/постановку и не подмешиваются. Два совместимых dev-ID имеют '
        'также дубликаты прежних контрольных запусков, которые не считаются независимыми задачами. '
        'ML/MC/линейная интерполяция/другие продолжения не запускались.','',
        'Основной допуск E33≤0,05 включает равенство. Катастрофический выброс здесь '
        'операционно определён как E33>1; это не утверждение о неприменимости метода. '
        'Материальное увеличение: ΔE>1e−10·max(1,E_before); это соглашение сравнения '
        'floating-point результатов, не граница ошибки. Все положительные ΔE отдельно '
