        f"**{s['recommendation']} как новый экспериментальный cubic/zero-профиль.** "
        f"Не пройдены заранее заданные условия: {', '.join(s['failed_gates']) or 'нет'}.",
        'GO, если получено, не означает замену production, доказанную непрерывную норму, '
        'сохранение всех условий теоремы, достаточную точность для всех52 или перенос на Test. '
        'Все регрессии и оставшиеся неточные случаи опубликованы. Производственный '
        'cubic/taper остаётся исходным. Дополнительных задач, продолжений, уточнений '
        'и массовых серий после этого эксперимента не запускается.','',
        f"Фактическая длительность run-фазы с подготовкой/IO: {session['wall_seconds']:.3f}с. "
