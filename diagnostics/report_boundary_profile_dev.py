if str(ROOT) not in sys.path:sys.path.insert(0,str(ROOT))
from diagnostics.boundary_profile_common import (atomic_json,csv_write,compare,max_error,read,require,sha,summary)


MATH_NOTE=r'''# Пространственная аппроксимация и граничное продолжение

## Что меняется в существующем коде

`chernov_solver.py::_apply` всегда строит тот же `CubicSpline(state.x,u,
extrapolate=False)`. Внутри рабочего окна значения совпадают для одной и той
же u. За окном сначала записывается0; только при boundary=taper эти нули
заменяются касательным продолжением со smoothstep. При boundary=zero эта
замена не выполняется. Финальная проекция ответа, временная квадратура,
число итераций, сдвиги и операторная формула не меняются:

S(τ)u(x)=¼u(x+2√(aτ))+¼u(x−2√(aτ))+½u(x+2bτ)+τc_R(x)u(x).

В S входит c_R, дрейф имеет знак плюс, λ остаётся в экспоненциальном весе.
Коэффициенты и их глобальные сертификаты не изменены. Zero уже является
допустимым вариантом ChernovConfig; код не заменяется и новые условия
построения внутреннего кубического сплайна не вводятся.

## Почему это не автоматически теорема о глобальном методе

1. На концах окна `q == edge` возвращается u_edge, а при `q > edge` или
   `q < edge` возвращается0. Если u_edge≠0, продолжение разрывно.
   Оно не принадлежит C_b/UC_b, когда эти пространства непрерывных функций
   требуются для выбранного теоретического обоснования. Zero не принуждает
   сами граничные узловые значения к нулю и не является здесь отдельным
   корректно поставленным решателем краевой задачи Дирихле.
2. Даже при нулевых граничных значениях остаётся излом производной: для
   узлов x=0,1,2,3 и u=(0,1,1,0) внутренний not-a-knot-сплайн
   p(x)=3x/2−x²/2 имеет p′(0)=3/2 и p′(3)=−3/2, а производная
   внешнего нуля равна0. Внутренний C²-сплайн остаётся корректным;
   глобальное гладкое продолжение из этого не следует.
3. Кубическая интерполяция не гарантирует положительность и контрактность
   в максимальной норме узлов. Конкретный контрпример непосредственно
   проверяется вызовом неизменённой `_apply` в тестах:
   x=(0,1,2,3), a=1/4, b=4, c_R=0, τ=1/16, boundary=zero.
   Для u=(0,1,1,0), ‖u‖узл=1, результат в x=1 равен67/64=1,046875>1.
   Для неотрицательных u=(1,0,0,0) результат в x=1 равен−1/64.
   Поэтому дискретную оценку ‖S_h(τ)u‖≤(1+τC)‖u‖ нельзя считать
   установленной только из формальных весов ¼,¼,½. Это свойство внутренней
   кубической реконструкции, а не новый математический оператор Ремизова.
4. Первоначальный forcing имеет компактный носитель внутри [-13,13], и
   его края равны0. Но повторные сдвиги S(τ)^k распространяют состояния;
   их носитель и значения на границе не обязаны оставаться нулевыми.
   Поэтому наличие исходного носителя внутри окна не доказывает отсутствие
   усечения после итераций. Ведётся поле boundary_state_max_abs, которое
   характеризует промежуточные состояния, а не итоговую ошибку E33.

Эти выводы — проверяемые свойства реализации и явные контрпримеры, а не
ссылка на непроверенную формулировку конкретной теоремы. Первоисточник
теоремы Ремизова в проекте отсутствует; её полные предпосылки не объявляются
проверенными. Для переноса глобальной теории на конечное окно нужны
отдельные оценки пространственной устойчивости, интерполяции и усечения,
в том числе при измельчении сетки/увеличении окна. Здесь таких серий нет.

## Следствие для решения об экспериментальном профиле

Zero убирает конкретный механизм внешнего касательного усиления taper,
но не сертифицирует всю пространственную аппроксимацию. Он не меняет
само уравнение или формулу S, однако меняет её реализацию на конечном окне.
Поэтому GO в отчёте, если эмпирические критерии выполнены, означает только
пригодность отдельно именованного экспериментального cubic/zero-профиля
на этой development-выборке. Производственный cubic/taper не заменяется.
Нельзя утверждать сохранение всех теоретических предпосылок, сходимость,
универсальную точность или перенос результата на Test.
'''


def report(out):
    plan=read(out/'plan.json');session=read(out/'session.json');require(session['complete'],'incomplete experiment')
    rows=[]
    selected_keys=('equation_id','category','E_before','family_id','expression_hash','structure_signature','complexity_level','regime','split')
    for task in plan['tasks']:
        before=read(ROOT/task['before_source']);after=read(out/'records'/(task['equation_id']+'.json'))
        require(after['plan_sha256']==sha(out/'plan.json'),'record plan mismatch')
        row=compare({k:task[k] for k in selected_keys},before,after);rows.append(row)
    s=summary(rows)
    csv_write(out/'before_after.csv',rows)
    csv_write(out/'regressions.csv',[r for r in rows if r['increased_unrounded']],fields=list(rows[0]))
    csv_write(out/'material_regressions.csv',[r for r in rows if r['material_regression']],fields=list(rows[0]))
    csv_write(out/'unresolved_cases.csv',[r for r in rows if r['pass_after'] is not True],fields=list(rows[0]))
    atomic_json(out/'summary.json',s)
    (out/'SPATIAL_ASSESSMENT.md').write_text(MATH_NOTE)
