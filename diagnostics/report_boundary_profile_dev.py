        'ошибки между узлами. По этой целевой выборке нельзя оценивать долю успеха на1000 задачах.','',
        '## Пространственные предпосылки и интерпретация','',
        'Математическая формула S не изменена; заменён только способ вычисления запросов '
        'за конечным окном. Это устранение конкретного внешнего механизма усиления, '
        'а не новая доказанная пространственная схема. SPATIAL_ASSESSMENT.md содержит '
        'разбор кода и независимые контрпримеры: zero может создавать скачок на границе; '
